//! FlexStack (Rust) node for the signed interoperability matrix.
//!
//! A complete ITS-S on the raw Ethernet link layer: CA basic service and DEN
//! service on BTP on a GeoNetworking router with security enabled
//! (`itsGnSecurity`) and the router's own signing (security profile by
//! ITS-AID) and verification. It signs with its own Authorization Ticket and
//! trusts only the Root CA and AA given on the command line: the ATs of the
//! other nodes are learned from the messages they send (signer `certificate`),
//! never preloaded.
//!
//! * CAMs: generated by the CA basic service (TS 103 900 generation rules);
//!   the node drives a small circular trajectory so that the heading changes
//!   by more than 4 degrees every 100 ms and CAMs are sent at 10 Hz. The AT is
//!   included once per second, the digest otherwise (TS 103 097 clause 7.1.1).
//! * DENMs: one new event (AppDENM_trigger) per `--denm-interval` ms, always
//!   signed with the certificate (TS 103 097 clause 7.1.2).
//!
//! Every signing and verification outcome, and every CAM / DENM delivered to
//! the facilities, is written to stdout as one JSON line (interop/README.md,
//! "Log format"). Mirrors `interop/python/interop_node.py`.

