#[derive(Parser, Debug)]
#[command(about = "FlexStack Rust node, signed interop matrix")]
struct Args {
    #[arg(long, default_value = "rust")]
    node: String,
    #[arg(long, default_value = "eth0")]
    iface: String,
    #[arg(long)]
    certs_dir: String,
    /// Trusted Root CA (file stem).
    #[arg(long, default_value = "root_ca")]
    root: String,
    /// Trusted AA (file stem).
    #[arg(long, default_value = "aa")]
    aa: String,
    /// Own AT (file stem; .cert and .key).
    #[arg(long)]
    at: String,
    #[arg(long, default_value_t = 2)]
    station_id: u32,
    #[arg(long, default_value_t = 41.3870)]
    lat: f64,
    #[arg(long, default_value_t = 2.1700)]
    lon: f64,
    /// Do not send CAMs.
    #[arg(long)]
    no_cam: bool,
    /// DENM interval in ms (0: no DENMs).
    #[arg(long, default_value_t = 1000)]
    denm_interval: u64,
}

static LOG: Mutex<()> = Mutex::new(());

fn now_ms() -> u128 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap()
        .as_millis()
}

/// One JSON line on stdout: `fields` is a list of `"key":value` items.
fn log(node: &str, event: &str, fields: &[String]) {
    let mut line = format!(
        "{{\"t_ms\":{},\"node\":\"{}\",\"event\":\"{}\"",
        now_ms(),
        node,
        event
    );
    for field in fields {
        line.push(',');
        line.push_str(field);
    }
    line.push('}');
    let _guard = LOG.lock().unwrap();
    let mut out = std::io::stdout().lock();
    let _ = writeln!(out, "{line}");
    let _ = out.flush();
}

fn s(key: &str, value: &str) -> String {
    format!("\"{key}\":\"{value}\"")
}

fn n(key: &str, value: i64) -> String {
    format!("\"{key}\":{value}")
}

fn b(key: &str, value: bool) -> String {
    format!("\"{key}\":{value}")
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|x| format!("{x:02x}")).collect()
}

/// (PSID, signer type, AT HashedId8) of an Ieee1609Dot2Data signed message.
fn signer_of(secured: &[u8]) -> (i64, &'static str, String) {
    let Some(data) = try_decode_ieee1609_dot2_data(secured) else {
        return (-1, "undecodable", String::new());
    };
    let Ieee1609Dot2Content::signedData(sd) = &data.content else {
        return (-1, "unsigned", String::new());
    };
    let psid = i64::try_from(&sd.tbs_data.header_info.psid.0).unwrap_or(-1);
    match &sd.signer {
        SignerIdentifier::digest(h) => (psid, "digest", hex(&h.0[..])),
        SignerIdentifier::certificate(certs) if certs.0.len() == 1 => {
            // HashedId8 of a P-256 certificate (TS 103 097 clause 6).
            let encoded = encode_certificate(&EtsiTs103097Certificate(certs.0[0].clone()));
            (psid, "certificate", hex(&compute_hashedid8(&encoded)))
        }
        _ => (psid, "other", String::new()),
    }
}

fn mac_of(iface: &str) -> [u8; 6] {
    let text = fs::read_to_string(format!("/sys/class/net/{iface}/address"))
        .unwrap_or_else(|e| panic!("MAC address of {iface}: {e}"));
    let mut mac = [0u8; 6];
    for (i, part) in text.trim().split(':').enumerate().take(6) {
        mac[i] = u8::from_str_radix(part, 16).expect("MAC address");
    }
    mac
}

fn main() {
    let args = Args::parse();
    let node = args.node.clone();
    let dir = Path::new(&args.certs_dir);
    let read = |name: String| fs::read(dir.join(&name)).unwrap_or_else(|e| panic!("{name}: {e}"));

    // ── Security: own AT, trust anchors only ─────────────────────────────
    let root = Certificate::from_bytes(&read(format!("{}.cert", args.root)), None);
    let aa = Certificate::from_bytes(&read(format!("{}.cert", args.aa)), Some(root.clone()));
    let at = Certificate::from_bytes(&read(format!("{}.cert", args.at)), Some(aa.clone()));
    let mut backend = EcdsaBackend::new();
    let key_id = backend.import_signing_key(&read(format!("{}.key", args.at)));
    let sign_library =
        CertificateLibrary::new(&backend, vec![root.clone()], vec![aa.clone()], vec![]);
    let mut sign_service = SignService::new(backend.clone(), sign_library);
    sign_service.add_own_certificate(OwnCertificate::new(at, key_id));
    if sign_service.cert_library.own_certificates.is_empty() {
        panic!("the AT was not accepted: it does not verify with the AA");
    }
    let verify_library = CertificateLibrary::new(&backend, vec![root], vec![aa], vec![]);

    // ── GeoNetworking with integrated signing and verification ───────────
    let mac = mac_of(&args.iface);
    let mut mib = Mib::new();
    mib.itsGnLocalGnAddr = GNAddress::new(M::GnMulticast, ST::PassengerCar, MID::new(mac));
    mib.itsGnIfType = GnIfType::ItsG5;
    mib.itsGnSecurity = GnSecurity::Enabled;
    let (gn_handle, gn_to_ll_rx, gn_to_btp_rx) =
        GNRouter::spawn(mib, Some(sign_service), Some(backend), Some(verify_library));
    let observer_node = node.clone();
    gn_handle.set_verify_observer(Box::new(move |message, confirm| {
        let (_, kind, at) = signer_of(message);
        log(
            &observer_node,
            "rx",
            &[
                n("its_aid", confirm.its_aid as i64),
                s("signer", kind),
                s("at", &at),
                s("report", &format!("{:?}", confirm.report)),
                b("verified", confirm.report == ReportVerify::Success),
            ],
        );
    }));
    let (btp_handle, btp_to_gn_rx) = BTPRouter::spawn(mib);

    // TX log: every frame the router passes to the link layer.
    let (ll_tx, ll_tx_rx) = mpsc::channel::<Vec<u8>>();
    let tx_node = node.clone();
    thread::spawn(move || {
        while let Ok(frame) = gn_to_ll_rx.recv() {
            if frame.len() > 4 {
                let basic = BasicHeader::decode(frame[0..4].try_into().unwrap());
                if matches!(basic.nh, BasicNH::SecuredPacket) {
                    let (psid, kind, at) = signer_of(&frame[4..]);
                    log(
                        &tx_node,
                        "tx",
                        &[
                            n("its_aid", psid),
                            s("signer", kind),
                            s("at", &at),
                            b("signed", true),
                        ],
                    );
                } else {
                    log(&tx_node, "tx", &[b("signed", false)]);
                }
            }
            if ll_tx.send(frame).is_err() {
                break;
            }
        }
    });

    let (ll_to_gn_tx, ll_to_gn_rx) = mpsc::channel::<Vec<u8>>();
    let raw_ll = RawLinkLayer::new(ll_to_gn_tx, ll_tx_rx, &args.iface, mac);
    assert!(
        mib.media_dependent_address_ok(Some(raw_ll.media_dependent_mid())),
        "itsGnLocalGnAddr MID must be the MAC address of the link layer"
    );
    raw_ll.start();
    let gn_rx = gn_handle.clone();
    thread::spawn(move || {
        while let Ok(packet) = ll_to_gn_rx.recv() {
            gn_rx.send_incoming_packet(packet);
        }
    });
    let btp_rx = btp_handle.clone();
    thread::spawn(move || {
        while let Ok(indication) = gn_to_btp_rx.recv() {
            btp_rx.send_gn_data_indication(indication);
        }
    });
    let gn_tx = gn_handle.clone();
    thread::spawn(move || {
        while let Ok(request) = btp_to_gn_rx.recv() {
            gn_tx.send_gn_data_request(request);
        }
    });

    // ── Facilities ───────────────────────────────────────────────────────
    let (ca, cam_rx) = CooperativeAwarenessBasicService::new(
        btp_handle.clone(),
        CamVehicleData {
            station_id: args.station_id,
            ..CamVehicleData::default()
        },
        None,
    );
    let (mut den, denm_rx) = DecentralizedEnvironmentalNotificationService::new(
        btp_handle.clone(),
        DenmVehicleData {
            station_id: args.station_id,
            station_type: 5,
        },
    );
    den.start();
    let cam_node = node.clone();
    thread::spawn(move || {
        while let Ok(cam) = cam_rx.recv() {
            log(
                &cam_node,
                "cam",
                &[
                    b("decoded", true),
                    n("station_id", cam.header.station_id.0 as i64),
                    n("protocol_version", cam.header.protocol_version.0 as i64),
                ],
            );
        }
    });
    let denm_node = node.clone();
    thread::spawn(move || {
        while let Ok(denm) = denm_rx.recv() {
            log(
                &denm_node,
                "denm",
                &[
                    b("decoded", true),
                    n("station_id", denm.header.station_id.0 as i64),
                    n("protocol_version", denm.header.protocol_version.0 as i64),
                ],
            );
        }
    });

    // ── Trajectory: 10 m circle at 10 m/s, a fix every 80 ms ─────────────
    let (cam_gps_tx, cam_gps_rx) = mpsc::channel::<GpsFix>();
    if !args.no_cam {
        ca.start(cam_gps_rx);
    }
    let position = Arc::new(Mutex::new((args.lat, args.lon)));
    let running = Arc::new(AtomicBool::new(true));
    {
        let position = Arc::clone(&position);
        let running = Arc::clone(&running);
        let gn_pos = gn_handle.clone();
        let (lat0, lon0) = (args.lat, args.lon);
        thread::spawn(move || {
            const PERIOD_S: f64 = 0.08;
            const SPEED: f64 = 10.0;
            const RADIUS: f64 = 10.0;
            const EARTH_R: f64 = 6_371_000.0;
            let mut angle: f64 = 0.0;
            while running.load(Ordering::Relaxed) {
                angle += SPEED * PERIOD_S / RADIUS;
                let north = RADIUS * angle.sin();
                let east = RADIUS * (1.0 - angle.cos());
                let lat = lat0 + (north / EARTH_R).to_degrees();
                let lon = lon0 + (east / (EARTH_R * lat0.to_radians().cos())).to_degrees();
                let heading = (angle + std::f64::consts::FRAC_PI_2).to_degrees() % 360.0;
                *position.lock().unwrap() = (lat, lon);
                let fix = GpsFix {
                    latitude: lat,
                    longitude: lon,
                    altitude_m: 0.0,
                    speed_mps: SPEED,
                    heading_deg: heading,
                    pai: true,
                    fix_time_ms: None,
                };
                let mut epv = LongPositionVector::decode([0u8; 24]);
                epv.update_from_gps_at(lat, lon, SPEED, heading, true, None);
                gn_pos.update_position_vector(epv);
                let _ = cam_gps_tx.send(fix);
                thread::sleep(Duration::from_secs_f64(PERIOD_S));
            }
        });
    }

    let stop = Arc::new(AtomicBool::new(false));
    {
        let stop = Arc::clone(&stop);
        ctrlc_handler(move || stop.store(true, Ordering::SeqCst));
    }
    log(&node, "start", &[s("stack", "flexstack-rust")]);
    let template = build_denm(&DENRequest::default(), &Default::default(), 0)
        .denm
        .management
        .event_position;
    let location = build_denm(&DENRequest::default(), &Default::default(), 0)
        .denm
        .location;
    let interval = Duration::from_millis(if args.denm_interval > 0 {
        args.denm_interval
    } else {
        1000
    });
    while !stop.load(Ordering::SeqCst) {
        thread::sleep(interval);
        if args.denm_interval == 0 || stop.load(Ordering::SeqCst) {
            continue;
        }
        let (lat, lon) = *position.lock().unwrap();
        den.set_ego_position((lat * 1e7) as i32, (lon * 1e7) as i32);
        let mut event_position = template.clone();
        event_position.latitude = Latitude((lat * 1e7) as i32);
        event_position.longitude = Longitude((lon * 1e7) as i32);
        let mut request = DenmRequest::new(event_position);
        request.situation = Some(SituationContainer::new(
            InformationQuality(1),
            CauseCodeV2::new(CauseCodeChoice::roadworks3(cdd::RoadworksSubCauseCode(0))),
            None,
            None,
            None,
            None,
        ));
        request.location = location.clone();
        let result = den.trigger(&request);
        log(&node, "denm_tx", &[b("accepted", result.is_ok())]);
    }
    running.store(false, Ordering::Relaxed);
    log(&node, "stop", &[]);
    std::process::exit(0);
}

/// SIGINT / SIGTERM handler without extra dependencies: a thread waiting on a
/// self-pipe would need libc, so the node polls a flag set from the handler.
fn ctrlc_handler<F: Fn() + Send + Sync + 'static>(f: F) {
    use std::sync::OnceLock;
    static HANDLER: OnceLock<Box<dyn Fn() + Send + Sync>> = OnceLock::new();
    let _ = HANDLER.set(Box::new(f));
    extern "C" fn on_signal(_: i32) {
        if let Some(handler) = HANDLER.get() {
            handler();
        }
    }
    extern "C" {
        fn signal(signum: i32, handler: extern "C" fn(i32)) -> usize;
    }
    // SAFETY: installing a handler that only stores to an atomic flag.
    unsafe {
        signal(2, on_signal); // SIGINT
        signal(15, on_signal); // SIGTERM
    }
}
